const normalizeHref = (href) => {
  try {
    const url = new URL(href);
    url.hash = "";
    return url.toString();
  } catch {
    return href;
  }
};

const publicationsByHref = new Map();

for (const publication of [
  ...manualPublications,
  ...automaticPublications
]) {
  const key = normalizeHref(publication.href);

  /*
   * Wpis ręczny ma pierwszeństwo przed automatycznym.
   */
  if (
    !publicationsByHref.has(key) ||
    publication.automatic !== true
  ) {
    publicationsByHref.set(key, publication);
  }
}

export const publications = [
  ...publicationsByHref.values()
];

/*
 * Archiwa są sortowane chronologicznie: od najstarszych do najnowszych.
 * Publikacje wyróżnione są sortowane od najnowszych do najstarszych.
 */

export const mediaPublications = publications
  .filter((publication) => publication.category === "media")
  .sort((a, b) => new Date(a.dateISO) - new Date(b.dateISO));

export const publicVoices = publications
  .filter((publication) => publication.category === "public")
  .sort((a, b) => new Date(a.dateISO) - new Date(b.dateISO));

export const committeeMaterials = publications
  .filter((publication) => publication.category === "committee")
  .sort((a, b) => new Date(a.dateISO) - new Date(b.dateISO));

export const featuredPublications = publications
  .filter((publication) => publication.featured)
  .sort((a, b) => new Date(b.dateISO) - new Date(a.dateISO));

export const publicationStats = {
  media: mediaPublications.length,
  public: publicVoices.length,
  committee: committeeMaterials.length
};
